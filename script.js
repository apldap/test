// 4. ИНИЦИАЛИЗАЦИЯ И ИНТЕРФЕЙС
// ==========================================================================
document.addEventListener("DOMContentLoaded", () => {
    

    // ========================================================================
    // 2. ГОРОД: ЕДИНЫЙ ФИЛЬТР ДЛЯ ИВЕНТОВ И ОРГАНИЗАЦИЙ
    // Город не является обязательным экраном. Он просто хранится в шапке.
    // ========================================================================
    const citySelect = document.getElementById("citySelect");
    const savedCity = localStorage.getItem("arakettikCity") || "bishkek";

    if (citySelect) {
        citySelect.value = [...citySelect.options].some(option => option.value === savedCity)
            ? savedCity
            : "bishkek";

        citySelect.addEventListener("change", () => {
            localStorage.setItem("arakettikCity", citySelect.value);
            renderEvents();
            renderOrganizations();
        });
    }

    // ========================================================================
    // 3. ОРГАНИЗАЦИИ: ПОИСК И ФИЛЬТРАЦИЯ ПО РЕГИОНУ
    // ========================================================================
    const organizationSearch = document.getElementById("organizationSearch");
    const organizationModal = document.getElementById("organizationModal");
    const organizationModalClose = document.getElementById("organizationModalClose");

    if (organizationSearch) {
        organizationSearch.addEventListener("input", renderOrganizations);
    }

    function closeModal(modal) {
        if (!modal) return;
        modal.classList.add("hidden");
        modal.setAttribute("aria-hidden", "true");
        document.body.style.overflow = "";
    }

    if (organizationModalClose && organizationModal) {
        organizationModalClose.addEventListener("click", (event) => {
            event.preventDefault();
            event.stopPropagation();
            closeModal(organizationModal);
        });

        organizationModal.addEventListener("click", (event) => {
            if (event.target === organizationModal) closeModal(organizationModal);
        });
    }

    renderOrganizations();

    // Переключение тем (день/ночь)
    const themeToggleBtn = document.getElementById("themeToggle");
    const currentTheme = localStorage.getItem("theme") || "dark";
    document.documentElement.setAttribute("data-theme", currentTheme);
    updateThemeIcon(currentTheme);

    if (themeToggleBtn) {
        themeToggleBtn.addEventListener("click", () => {
            let theme = document.documentElement.getAttribute("data-theme");
            let newTheme = theme === "dark" ? "light" : "dark";
            document.documentElement.setAttribute("data-theme", newTheme);
            localStorage.setItem("theme", newTheme);
            updateThemeIcon(newTheme);
        });
    }

    function updateThemeIcon(theme) {
        if (themeToggleBtn) {
            themeToggleBtn.querySelector("i").className = theme === "dark" ? "fa-solid fa-sun" : "fa-solid fa-moon";
        }
    }

    // Мобильное меню
    const menuToggle = document.getElementById("menuToggle");
    const navMenu = document.getElementById("navMenu");
    if (menuToggle && navMenu) {
        menuToggle.addEventListener("click", () => {
            navMenu.classList.toggle("open");
            menuToggle.querySelector("i").className = navMenu.classList.contains("open") ? "fa-solid fa-xmark" : "fa-solid fa-bars";
        });
    }

    // ==========================================================================
    // 4. ИВЕНТЫ (ПОИСК И ФИЛЬТР)
    // ==========================================================================
    const eventsGrid = document.getElementById("eventsGrid");
    const searchInput = document.getElementById("searchInput");
    const filterBtns = document.querySelectorAll(".filter-btn");
    let currentFilter = "all", searchQuery = "";

    function renderEvents() {
        if (!eventsGrid) return;
        eventsGrid.innerHTML = "";
        const selectedCity = document.getElementById("citySelect")?.value || localStorage.getItem("arakettikCity") || "bishkek";
        const allEvents = [...eventsData, ...approvedEventsData];
        const filteredEvents = allEvents.filter(event => {
            const title = String(event.title || "");
            const desc = String(event.desc || event.description || "");
            return event.city === selectedCity &&
                (currentFilter === "all" || event.category === currentFilter) &&
                (title.toLowerCase().includes(searchQuery.toLowerCase()) || desc.toLowerCase().includes(searchQuery.toLowerCase()));
        });

        if (filteredEvents.length === 0) {
            eventsGrid.innerHTML = `<div class="glass-card" style="grid-column:1/-1;padding:40px;text-align:center;color:var(--text-muted);">Ничего не найдено 🚀</div>`;
            return;
        }

        filteredEvents.forEach((event, eventIndex) => {
            const viewId = event.approvedId ? `approved-${event.approvedId}` : `local-${event.id}`;
            const image = event.imageData ? `<img class="event-card-image" src="${event.imageData}" alt="${escapeHtml(event.title || "Мероприятие")}">` : "";
            const dateText = event.date || "Дата уточняется";
            const desc = event.desc || event.description || "";
            eventsGrid.innerHTML += `
                <article class="glass-card event-card ${event.approvedId ? "remote-event-card" : ""}">
                    ${image}
                    <div class="event-badge-row">
                        <span class="cat-tag cat-${event.category || "webinars"}">${event.categoryName || event.category || "Мероприятие"}</span>
                        <span class="event-date"><i class="fa-regular fa-calendar"></i> ${escapeHtml(dateText)}</span>
                    </div>
                    <div class="event-body">
                        <h3>${escapeHtml(event.title || "Без названия")}</h3>
                        <p>${escapeHtml(desc)}</p>
                    </div>
                    <div class="event-footer">
                        <button class="btn btn-secondary btn-block" onclick="openEventById('${viewId}')">Подробнее</button>
                    </div>
                </article>
            `;
        });
    }

    window.__renderEventsNow = renderEvents;

    if (searchInput) searchInput.addEventListener("input", (e) => { searchQuery = e.target.value; renderEvents(); });
    filterBtns.forEach(btn => {
        btn.addEventListener("click", () => {
            filterBtns.forEach(b => b.classList.remove("active"));
            btn.classList.add("active");
            currentFilter = btn.getAttribute("data-filter");
            renderEvents();
        });
    });
    renderEvents();

    // ==========================================================================
    // 5. РЕНДЕР БАЗЫ ЗНАНИЙ (ХАБА)
    // ==========================================================================
    const hubContent = document.getElementById("hubContent");
    const hubTabBtns = document.querySelectorAll(".hub-tab-btn");

    function renderHub(tabName) {
        if (!hubContent) return;
        hubContent.innerHTML = "";
        hubData[tabName].forEach((article, index) => {
            let iconClass = tabName === "mun" ? "fa-solid fa-globe" : tabName === "debates" ? "fa-solid fa-comments" : "fa-solid fa-brain";
            
            hubContent.innerHTML += `
                <div class="glass-card article-card">
                    <div class="article-icon"><i class="${iconClass}"></i></div>
                    <h3>${article.title}</h3>
                    <p>${article.desc}</p>
                    <button class="read-link" onclick="openArticle('${tabName}', ${index})">
                        Читать гайд <i class="fa-solid fa-arrow-right"></i>
                    </button>
                </div>
            `;
        });
    }

    hubTabBtns.forEach(btn => {
        btn.addEventListener("click", () => {
            hubTabBtns.forEach(b => b.classList.remove("active"));
            btn.classList.add("active");
            renderHub(btn.getAttribute("data-tab"));
        });
    });

    renderHub("mun");

    // ==========================================================================
    // 6. ФОРМА ОРГАНИЗАТОРА: МЕРОПРИЯТИЕ ИЛИ ОРГАНИЗАЦИЯ
    // ==========================================================================
    const suggestForm = document.getElementById("suggestForm");
    const formSuccess = document.getElementById("formSuccess");
    const submissionType = document.getElementById("submissionType");
    const submissionTypeButtons = document.querySelectorAll(".submission-type-btn");
    const submissionCity = document.getElementById("submissionCity");
    const cityForForm = document.getElementById("citySelect");

    const APPLICATION_API_URL = "https://arakettik-api.erzanabdimitalipov07.workers.dev/";

    function updateSubmissionForm(type) {
        if (submissionType) submissionType.value = type;
        submissionTypeButtons.forEach(button => button.classList.toggle("active", button.dataset.submissionType === type));
        document.querySelectorAll(".event-only-field").forEach(el => el.classList.toggle("hidden", type !== "event"));
        document.querySelectorAll(".organization-only-field").forEach(el => el.classList.toggle("hidden", type !== "organization"));
        const descriptionLabel = document.getElementById("descriptionLabel");
        if (descriptionLabel) descriptionLabel.textContent = type === "event" ? "Описание мероприятия" : "Подробное описание организации";
    }

    submissionTypeButtons.forEach(button => {
        button.addEventListener("click", () => updateSubmissionForm(button.dataset.submissionType));
    });

    if (submissionCity && cityForForm) {
        submissionCity.value = cityForForm.value;
        cityForForm.addEventListener("change", () => { submissionCity.value = cityForForm.value; });
    }

    const imageInput = document.getElementById("submissionImage");
    const imagePreview = document.getElementById("imagePreview");
    let selectedImageData = "";

    function resizeImage(file, maxSize = 1400, quality = 0.78) {
        return new Promise((resolve, reject) => {
            const reader = new FileReader();
            reader.onload = () => {
                const image = new Image();
                image.onload = () => {
                    const scale = Math.min(1, maxSize / Math.max(image.width, image.height));
                    const canvas = document.createElement("canvas");
                    canvas.width = Math.max(1, Math.round(image.width * scale));
                    canvas.height = Math.max(1, Math.round(image.height * scale));
                    const ctx = canvas.getContext("2d");
                    ctx.drawImage(image, 0, 0, canvas.width, canvas.height);
                    resolve(canvas.toDataURL("image/jpeg", quality));
                };
                image.onerror = reject;
                image.src = reader.result;
            };
            reader.onerror = reject;
            reader.readAsDataURL(file);
        });
    }

    if (imageInput) {
        imageInput.addEventListener("change", async () => {
            const file = imageInput.files?.[0];
            if (!file) { selectedImageData = ""; imagePreview?.classList.add("hidden"); return; }
            if (file.size > 5 * 1024 * 1024) {
                alert("Фотография слишком большая. Выберите файл до 5 МБ.");
                imageInput.value = "";
                return;
            }
            try {
                selectedImageData = await resizeImage(file);
                if (imagePreview) {
                    imagePreview.innerHTML = `<img src="${selectedImageData}" alt="Предпросмотр">`;
                    imagePreview.classList.remove("hidden");
                }
            } catch (error) {
                console.error(error);
                alert("Не удалось обработать фотографию.");
            }
        });
    }

    if (suggestForm) {
        suggestForm.addEventListener("submit", async (e) => {
            e.preventDefault();
            const honeypot = document.getElementById("website")?.value.trim();
            if (honeypot) return;

            const type = submissionType?.value || "event";
            const submitButton = suggestForm.querySelector('button[type="submit"]');
            const originalText = submitButton?.textContent || "Отправить на модерацию";
            const selectedOption = submissionCity?.selectedOptions?.[0];
            const city = submissionCity?.value || cityForForm?.value || "bishkek";
            const cityName = selectedOption?.textContent?.trim() || city;

            const payload = {
                type,
                title: type === "event" ? document.getElementById("eventTitle")?.value.trim() : document.getElementById("organizationName")?.value.trim(),
                organization: type === "event" ? document.getElementById("eventOrganizer")?.value.trim() : document.getElementById("organizationName")?.value.trim(),
                category: type === "event" ? document.getElementById("eventCat")?.value : "organization",
                categoryName: type === "event" ? document.getElementById("eventCat")?.selectedOptions?.[0]?.textContent : "Организация",
                description: document.getElementById("eventDesc")?.value.trim(),
                activity: document.getElementById("organizationActivity")?.value.trim(),
                history: document.getElementById("organizationHistory")?.value.trim(),
                address: type === "event" ? document.getElementById("eventLocation")?.value.trim() : document.getElementById("organizationAddress")?.value.trim(),
                date: type === "event" ? document.getElementById("eventDate")?.value : "",
                time: type === "event" ? document.getElementById("eventTime")?.value : "",
                registrationLink: document.getElementById("registrationLink")?.value.trim(),
                website: document.getElementById("organizationWebsite")?.value.trim(),
                contact: document.getElementById("contactPhone")?.value.trim(),
                socialLink: document.getElementById("socialLink")?.value.trim(),
                city,
                cityName,
                imageData: selectedImageData
            };

            if (!payload.title || !payload.description || !payload.contact) {
                alert("Заполните название, описание и номер телефона.");
                return;
            }
            if (type === "event" && (!payload.date || !payload.registrationLink || !payload.organization)) {
                alert("Для мероприятия заполните организатора, дату и ссылку на регистрацию.");
                return;
            }
            if (type === "organization" && (!payload.activity || !payload.address)) {
                alert("Для организации заполните направления деятельности и адрес.");
                return;
            }

            try {
                if (submitButton) { submitButton.disabled = true; submitButton.textContent = "Отправляем..."; }
                const response = await fetch(APPLICATION_API_URL, {
                    method: "POST",
                    headers: { "Content-Type": "application/json" },
                    body: JSON.stringify(payload)
                });
                const result = await response.json().catch(() => ({}));
                if (!response.ok || result.success !== true) throw new Error(result.message || result.error || "Не удалось отправить заявку");

                suggestForm.reset();
                selectedImageData = "";
                if (imagePreview) { imagePreview.innerHTML = ""; imagePreview.classList.add("hidden"); }
                if (formSuccess) formSuccess.classList.remove("hidden");
                suggestForm.classList.add("hidden");
            } catch (error) {
                console.error("Ошибка отправки заявки:", error);
                alert("Не удалось отправить заявку: " + error.message);
            } finally {
                if (submitButton) { submitButton.disabled = false; submitButton.textContent = originalText; }
            }
        });
    }

    // ==========================================================================
    // ОДОБРЕННЫЕ ИВЕНТЫ: ПОДГРУЗКА И ПЕРИОДИЧЕСКОЕ ОБНОВЛЕНИЕ
    // ==========================================================================
    loadApprovedEvents();
    loadApprovedOrganizations();
    setInterval(() => { loadApprovedEvents(); loadApprovedOrganizations(); }, 30000);

    // ==========================================================================
    // 7. ЗАКРЫТИЕ МОДАЛЬНОГО ОКНА СТАТЕЙ
    // ==========================================================================
    const articleModal = document.getElementById("articleModal");
    const modalClose = document.getElementById("modalClose");

    if (modalClose && articleModal) {
        modalClose.addEventListener("click", (event) => {
            event.preventDefault();
            event.stopPropagation();
            closeModal(articleModal);
        });

        articleModal.addEventListener("click", (event) => {
            if (event.target === articleModal) closeModal(articleModal);
        });
    }

    // ========================================================================
    // 9. ЗАКРЫТИЕ МОДАЛЬНЫХ ОКОН ПО ESC
    // ========================================================================
    document.addEventListener("keydown", (event) => {
        if (event.key !== "Escape") return;
        const openModals = document.querySelectorAll(".modal:not(.hidden)");
        openModals.forEach(modal => closeModal(modal));
    });

    // ========================================================================
    // 10. FAQ АККОРДЕОН
    // ==========================================================================
    document.querySelectorAll(".faq-question").forEach(question => {
        question.addEventListener("click", () => {
            const item = question.parentElement;
            const answer = item.querySelector(".faq-answer");
            if (item.classList.contains("open")) {
                answer.style.maxHeight = null; 
                item.classList.remove("open");
            } else {
                document.querySelectorAll(".faq-item").forEach(i => { 
                    i.classList.remove("open"); 
                    i.querySelector(".faq-answer").style.maxHeight = null; 
                });
                item.classList.add("open"); 
                answer.style.maxHeight = answer.scrollHeight + "px";
            }
        });
    });
});
